"""Report generation: structured JSON export and a Markdown summary."""

from __future__ import annotations

from pathlib import Path

from scounter import utils
from scounter.collector import CollectionResult


def write_reports(result: CollectionResult, output_root: Path) -> dict[str, Path]:
    """Write metadata.json and report.md. Return their paths."""
    target_dir = output_root / utils.sanitize(result.target)
    target_dir.mkdir(parents=True, exist_ok=True)

    metadata_path = target_dir / "metadata.json"
    report_path = target_dir / "report.md"

    utils.write_json(result, metadata_path)
    report_path.write_text(_render_markdown(result), encoding="utf-8")
    return {"metadata": metadata_path, "report": report_path}


def _render_markdown(result: CollectionResult) -> str:
    p = result.profile
    c = result.counts
    lines: list[str] = []
    lines.append(f"# Instagram Archive — @{result.target}")
    lines.append("")
    lines.append(f"- Generated: `{result.finished_at}`")
    lines.append(f"- Authenticated: {'yes (cookies)' if result.authenticated else 'no'}")
    lines.append("")

    lines.append("## Profile")
    lines.append("")
    lines.append(f"- **Name:** {p.get('full_name', '')}")
    lines.append(f"- **Username:** @{p.get('username', '')}")
    lines.append(f"- **User ID:** `{p.get('user_id', '')}`")
    lines.append(f"- **Followers:** {(p.get('followers') or 0):,}")
    lines.append(f"- **Following:** {(p.get('followees') or 0):,}")
    lines.append(f"- **Posts:** {(p.get('posts_count') or 0):,}")
    lines.append(f"- **Verified:** {p.get('is_verified')}")
    lines.append(f"- **Private:** {p.get('is_private')}")
    lines.append(f"- **Business:** {p.get('is_business')} "
                 f"({p.get('business_category') or p.get('category') or 'n/a'})")
    if p.get("external_url"):
        lines.append(f"- **External URL:** {p['external_url']}")
    if p.get("biography"):
        lines.append("")
        lines.append("> " + str(p["biography"]).replace("\n", "\n> "))
    lines.append("")

    lines.append("## Collection Summary")
    lines.append("")
    lines.append("| Category | Manifested | Downloaded |")
    lines.append("|----------|------------|------------|")
    for kind in ("posts", "reels", "stories", "highlights", "tagged"):
        total = c.get(kind, 0)
        done = c.get(f"{kind}_done", 0)
        lines.append(f"| {kind.capitalize()} | {total} | {done} |")
    lines.append(f"| **Total** | {c.get('manifested', 0)} | {c.get('downloaded', 0)} |")
    missing = c.get("missing", 0)
    if missing:
        lines.append("")
        lines.append(f"> ⚠ {missing} item(s) not yet downloaded — re-run to resume.")
    lines.append("")

    if result.errors:
        lines.append("## Errors")
        lines.append("")
        for err in result.errors:
            lines.append(f"- {err}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by scounter — cookies-only, full-HD Instagram archiver.*")
    lines.append("")
    return "\n".join(lines)
